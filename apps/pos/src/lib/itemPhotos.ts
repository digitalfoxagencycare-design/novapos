export function getCuratedPhotoForItem(name: string): string {
  if (!name) return 'https://images.unsplash.com/photo-1546069901-ba9599a7e63c?w=500&auto=format&fit=crop&q=80';
  
  // Clean string: lowercase, remove punctuation, portion numbers, extra spaces
  const clean = name
    .toLowerCase()
    .replace(/\(.*?\)/g, '')
    .replace(/[0-9]+(\s*(pcs|pc|g|kg|ml|l|half|full))?/gi, '')
    .replace(/[^a-z0-9\s]/g, ' ')
    .trim();

  // 1. Direct key match in dictionary
  if (CURATED_FOOD_PHOTOS[clean]) {
    return CURATED_FOOD_PHOTOS[clean];
  }

  // 2. Specific multi-word phrases first
  const multiWordKeys = Object.keys(CURATED_FOOD_PHOTOS).filter((k) => k.includes(' '));
  for (const key of multiWordKeys) {
    if (clean.includes(key) || key.includes(clean)) {
      return CURATED_FOOD_PHOTOS[key];
    }
  }

  // 3. Single-word token matches
  const tokens = clean.split(/\s+/).filter(Boolean);
  for (const token of tokens) {
    if (CURATED_FOOD_PHOTOS[token]) {
      return CURATED_FOOD_PHOTOS[token];
    }
    // Check partial token matches (e.g. "idly" matches "idli")
    if (token === 'idly' || token === 'idli' || token === 'idlis' || token === 'idlies') {
      return CURATED_FOOD_PHOTOS['idly'];
    }
    if (token === 'dosa' || token === 'dosai' || token === 'dose') {
      return CURATED_FOOD_PHOTOS['dosa'];
    }
    if (token === 'biryani' || token === 'biriyani' || token === 'briyani') {
      return CURATED_FOOD_PHOTOS['biryani'];
    }
    if (token === 'roti' || token === 'rotis' || token === 'phulka' || token === 'chapati' || token === 'chapathi') {
      return CURATED_FOOD_PHOTOS['roti'];
    }
    if (token === 'paneer' || token === 'panir') {
      return CURATED_FOOD_PHOTOS['paneer'];
    }
    if (token === 'chicken') {
      return CURATED_FOOD_PHOTOS['chicken'];
    }
    if (token === 'mutton') {
      return CURATED_FOOD_PHOTOS['mutton'];
    }
    if (token === 'fish' || token === 'prawn' || token === 'prawns') {
      return CURATED_FOOD_PHOTOS['fish'];
    }
    if (token === 'corn') {
      return CURATED_FOOD_PHOTOS['crispy corn'];
    }
  }

  // 4. Fallback appetizing restaurant gourmet photo
  return 'https://images.unsplash.com/photo-1546069901-ba9599a7e63c?w=500&auto=format&fit=crop&q=80';
}
